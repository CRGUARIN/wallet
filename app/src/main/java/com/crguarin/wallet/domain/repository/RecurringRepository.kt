package com.crguarin.wallet.domain.repository

import com.crguarin.wallet.domain.model.Transaction
import com.crguarin.wallet.domain.model.TransactionDetails
import com.crguarin.wallet.domain.model.recurring.OccurrenceResult
import com.crguarin.wallet.domain.model.recurring.RecurringPayment
import kotlinx.coroutines.flow.Flow
import java.time.LocalDate

interface RecurringRepository {
    fun observeAll(): Flow<List<RecurringPayment>>

    fun observe(id: Long): Flow<RecurringPayment?>

    suspend fun get(id: Long): RecurringPayment?

    suspend fun getAll(): List<RecurringPayment>

    suspend fun save(payment: RecurringPayment): Long

    /** Deletes the payment and sets recurring_id = NULL on its transactions, in one DB transaction. */
    suspend fun delete(id: Long)

    /**
     * In one DB transaction: if the stored nextDueDate equals [expectedDueDate], inserts [transaction]
     * (when not null, with recurringId = [paymentId]) and sets nextDueDate = [newNextDueDate].
     * Returns Recorded, Skipped (transaction null) or AlreadyHandled (nothing changed).
     */
    suspend fun completeOccurrence(
        paymentId: Long,
        expectedDueDate: LocalDate,
        transaction: Transaction?,
        newNextDueDate: LocalDate,
    ): OccurrenceResult

    /** Latest transactions generated by the payment, newest first. */
    fun observeGeneratedTransactions(
        paymentId: Long,
        limit: Int,
    ): Flow<List<TransactionDetails>>

    suspend fun countByAccount(accountId: Long): Int

    suspend fun countByCategory(categoryId: Long): Int
}
